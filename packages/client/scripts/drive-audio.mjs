import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
const url = process.env.WILDCARD_URL ?? 'http://127.0.0.1:5173';
const out = process.env.WILDCARD_SHOTS ?? 'shots-audio';
await mkdir(out, { recursive: true });
const browser = await chromium.launch();
try {
  const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
  const errors = [], failed = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('response', r => { if (r.url().includes('/audio/') && r.status() >= 400) failed.push(r.url()); });
  await page.addInitScript(() => {
    window.audioStarts = 0; window.audioStops = 0;
    const create = AudioContext.prototype.createBufferSource;
    AudioContext.prototype.createBufferSource = function (...args) {
      const source = create.apply(this, args), start = source.start.bind(source), stop = source.stop.bind(source);
      source.start = (...args) => { window.audioStarts++; return start(...args); };
      source.stop = (...args) => { window.audioStops++; return stop(...args); };
      return source;
    };
    const NativeAudio = window.Audio;
    window.Audio = function (...args) { const media = new NativeAudio(...args); window.tableMusic = media; return media; };
  });
  await page.goto(`${url}/test/fixtures/table-pacing.html`);
  await page.getByRole('button', { name: 'ゲーム開始', exact: true }).click();
  await page.waitForFunction(() => window.audioStarts >= 4);
  await page.waitForFunction(() => window.tableMusic?.currentTime > .2 && !window.tableMusic.paused);
  await page.waitForTimeout(1500);
  const played = await page.evaluate(() => window.audioStarts);
  await page.getByRole('button', { name: '卓の情報', exact: true }).click();
  await page.getByRole('tab', { name: 'サウンド', exact: true }).click();
  await page.getByRole('checkbox', { name: 'ミュート', exact: true }).check();
  assert.equal(await page.evaluate(() => window.tableMusic.paused), true);
  assert.equal(await page.getByRole('button', { name: '効果音を試す' }).isDisabled(), true);
  await page.waitForTimeout(400);
  assert.equal(await page.evaluate(() => window.audioStarts), played);
  await page.getByRole('checkbox', { name: 'ミュート', exact: true }).uncheck();
  await page.getByRole('button', { name: '効果音を試す' }).click();
  await page.waitForFunction(before => window.audioStarts > before, played);
  const volume = async (name, value) => {
    const slider = page.getByRole('slider', { name });
    await slider.press('Home');
    for (let i = 0; i < value; i++) await slider.press('ArrowRight');
  };
  await volume(/^BGM/, 0);
  assert.equal(await page.evaluate(() => window.tableMusic.paused), true);
  await volume(/^BGM/, 12);
  await page.waitForFunction(() => !window.tableMusic.paused);
  await volume(/^効果音/, 35);
  await page.getByText('音源クレジット', { exact: true }).click();
  assert.equal(await page.locator('.sound-credits a').count(), 3);
  await page.screenshot({ path: `${out}/settings.png` });
  await page.evaluate(() => { Object.defineProperty(document, 'hidden', { configurable: true, value: true }); document.dispatchEvent(new Event('visibilitychange')); });
  assert.equal(await page.evaluate(() => window.tableMusic.paused), true);
  await page.evaluate(() => { Object.defineProperty(document, 'hidden', { configurable: true, value: false }); document.dispatchEvent(new Event('visibilitychange')); });
  await page.waitForFunction(() => !window.tableMusic.paused);
  await page.getByRole('checkbox', { name: 'ミュート', exact: true }).check();
  await page.reload();
  await page.getByRole('button', { name: '卓の情報', exact: true }).click();
  await page.getByRole('tab', { name: 'サウンド', exact: true }).click();
  assert.equal(await page.getByRole('checkbox', { name: 'ミュート' }).isChecked(), true);
  assert.equal(await page.getByRole('slider', { name: /^効果音/ }).inputValue(), '35');
  assert.equal(await page.getByRole('slider', { name: /^BGM/ }).inputValue(), '12');
  await page.getByRole('checkbox', { name: 'ミュート' }).uncheck();
  await page.goto(url);
  await page.getByRole('tab', { name: 'ソロ', exact: false }).click();
  await page.getByRole('button', { name: 'はじめる', exact: true }).click();
  await page.getByRole('button', { name: 'ゲーム開始', exact: true }).click();
  await page.waitForFunction(() => window.tableMusic?.currentTime > .1);
  await page.getByRole('button', { name: 'もどる', exact: true }).click();
  assert.equal(await page.evaluate(() => window.tableMusic.paused), true, 'Leaving the table stops music');
  const stopped = await page.evaluate(() => window.audioStarts);
  await page.waitForTimeout(1400);
  assert.equal(await page.evaluate(() => window.audioStarts), stopped, 'No queued sounds after leaving');
  assert.deepEqual(errors, []); assert.deepEqual(failed, []);
  console.log('Actual decoded effects/BGM playback, independent volume, mute persistence, hidden-tab pause and table cleanup: passed');
} finally { await browser.close(); }
